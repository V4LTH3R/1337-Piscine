#include <unistd.h>

int	main(int ac, char **av)
{
	int	count;
	int	index;

	count = ac - 1;
	while (count > 0)
	{
		index = 0;
		while (av[count][index])
		{
			write(1, &av[count][index], 1);
			index++;
		}
		write(1, "\n", 1);
		count--;
	}
}
