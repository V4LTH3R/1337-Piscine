void	ft_sort_int_tab(int *tab, int size)
{
	int	i;
	int	j;
	int	fdy;

	i = 0;
	while (i < size - 1)
	{
		j = 0;
		while (j < size - 1)
		{
			if (tab[j] > tab[j + 1])
			{
				fdy = tab[j];
				tab[j] = tab[j + 1];
				tab[j + 1] = fdy;
			}
			j++;
		}
		i++;
	}
}
