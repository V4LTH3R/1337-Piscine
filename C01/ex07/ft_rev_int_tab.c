void	ft_rev_int_tab(int *tab, int size)
{
	int	i;
	int	fdy;

	i = 0;
	size--;
	while (size > i)
	{
		fdy = tab[i];
		tab[i] = tab[size];
		tab[size] = fdy;
		i++;
		size--;
	}
}

